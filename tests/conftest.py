def ballots_html(*members: tuple[int, str, str, str]) -> str:
    """Build a nominal vote page from (mp id, name, group, vote) tuples."""
    rows = "".join(
        f"""<tr valign="top">
<td nowrap align="right">{number}.</td>
<td><a href="/ords/pls/parlam/structura2015.mp?idm={mp_id}&cam=2&leg=2024">{name}</a></td>
<td align="center">{group}</td>
<td align="center" nowrap>
{vote}
</td>
</tr>"""
        for number, (mp_id, name, group, vote) in enumerate(members, start=1)
    )
    return f"<table>{rows}</table>"


class FakeSource:
    """An in-memory stand-in for CdepClient."""

    def __init__(
        self,
        days: dict[date, str] | None = None,
        ballots: dict[int, str] | None = None,
    ) -> None:
        self.days = days or {}
        self.ballots = ballots or {}
        # Alphabetical member lists, one per chamber.
        self.members: dict = {}
        self.calendar_requests: list[tuple[int, int]] = []

    def sitting_days(self, year: int, month: int) -> str:
        self.calendar_requests.append((year, month))
        return "".join(
            f",{day:%Y%m%d}" for day in self.days if (day.year, day.month) == (year, month)
        )

    def day_page(self, day: date) -> str:
        return self.days[day]

    def ballots_page(self, vote_id: int) -> str:
        return self.ballots[vote_id]

    def members_page(self, chamber, legislature: int) -> str:
        return self.members.get(chamber, "")


class FakeDb:
    """Mimics the part of the Supabase client the loader uses.

    Rows are stored per table under their conflict key, so upserting the same
    data twice leaves the same contents, as in Postgres.
    """

    def __init__(self) -> None:
        self.tables: dict[str, dict[tuple, dict]] = {}
        self.rpc_calls: list[str] = []
        self._next_id = 1

    # Tables whose primary key is generated by the database.
    GENERATED_IDS = frozenset({"parties", "mps"})

    def table(self, name: str) -> _FakeTable:
        return _FakeTable(self, name)

    def rpc(self, name: str) -> _FakeQuery:
        self.rpc_calls.append(name)
        return _FakeQuery([])

    def rows(self, name: str) -> list[dict]:
        return list(self.tables.get(name, {}).values())


class _FakeTable:
    def __init__(self, db: FakeDb, name: str) -> None:
        self._db = db
        self._name = name

    def update(self, values: dict) -> _FakeUpdate:
        return _FakeUpdate(self._db, self._name, values)

    def upsert(self, rows: list[dict], *, on_conflict: str) -> _FakeQuery:
        stored = self._db.tables.setdefault(self._name, {})
        columns = on_conflict.split(",")
        saved = []
        for row in rows:
            key = tuple(row[column] for column in columns)
            merged = {**stored.get(key, {}), **row}
            if "id" not in merged and self._name in FakeDb.GENERATED_IDS:
                merged["id"] = self._db._next_id
                self._db._next_id += 1
            stored[key] = merged
            saved.append(dict(merged))
        return _FakeQuery(saved)


class _FakeUpdate:
    """An update narrowed by eq() and in_() filters, applied on execute()."""

    def __init__(self, db: FakeDb, name: str, values: dict) -> None:
        self._db = db
        self._name = name
        self._values = values
        self._filters: list = []

    def eq(self, column: str, value) -> _FakeUpdate:
        self._filters.append(lambda row: row.get(column) == value)
        return self

    def in_(self, column: str, values: list) -> _FakeUpdate:
        self._filters.append(lambda row: row.get(column) in values)
        return self

    def execute(self) -> _FakeQuery:
        changed = []
        for row in self._db.tables.get(self._name, {}).values():
            if all(matches(row) for matches in self._filters):
                row.update(self._values)
                changed.append(dict(row))
        return _FakeQuery(changed)


class _FakeQuery:
    def __init__(self, data: list[dict]) -> None:
        self.data = data

    def execute(self) -> _FakeQuery:
        return self


def members_html(*members: tuple[int, str, int | None], chamber: int = 2) -> str:
    """Build a member list from (mp id, name, constituency number) tuples.

    A constituency of None makes a nationally elected member.
    """
    rows = ""
    for position, (mp_id, name, constituency) in enumerate(members, start=1):
        seat = (
            f'<a href="/ords/pls/parlam/structura2015.ce?cir={constituency}&leg=2024">'
            f"{constituency} / NAME</a>"
            if constituency
            else "la nivel naţional"
        )
        rows += (
            f'<tr><td>{position}.</td><td><b><a href="/ords/pls/parlam/structura2015.mp'
            f'?idm={mp_id}&cam={chamber}&leg=2024">{name}</a></b></td>'
            f"<td colspan=2>{seat}</td><td>PSD</td></tr>"
        )
    return f"<table>{rows}</table>"
